#include "push_swap.h"

/**
 * =========================================================================
 * FUNCTION: copy_stack
 * =========================================================================
 * OVERVIEW:
 *  Captures a snapshot array of stack A by recording pointers to each node
 *  in sequential order. Allocates via s_alloc and serves as a restoration
 *  reference during pivot tuning simulations.
 *
 * EXECUTION SCHEMA:
 *
 *   config->nums.a
 *         │
 *         ▼
 *   s_alloc(size * sizeof(t_stack *))
 *         │
 *         ├── [NULL] ──────────────────> g_free() + exit(1)
 *         │
 *         ▼ [Valid array]
 *   Loop i from 0 to size - 1:
 *         copy[i] = tmp
 *         tmp = tmp->next
 *         │
 *         ▼
 *   Return copy
 *
 * PARAMETERS:
 *  - config {t_config *}: Program context containing stack A and size.
 *
 * RETURNS:
 *  - {t_stack **}: Array of pointers referencing stack A nodes in order.
 *  - Aborts execution with status 1 on allocation failure.
 *
 * COMPLEXITY:
 *  - Time Complexity:  O(N), where N is config->nums.size.
 *  - Space Complexity: O(N) tracked heap memory for pointer array.
 *
 * EDGE CASES & ASSUMPTIONS:
 *  - Assumes stack A contains at least 'config->nums.size' linked nodes.
 *  - Relies on s_alloc; triggers full garbage cleanup before exiting on OOM.
 * =========================================================================
 */
static t_stack	**copy_stack(t_config *config)
{
	t_stack	**copy;
	t_stack	*tmp;
	int		i;

	i = 0;
	tmp = config->nums.a;
	copy = s_alloc(config->nums.size * sizeof(t_stack *));
	if (!copy)
		exit((g_free(), 1));
	while (i < config->nums.size)
	{
		copy[i++] = tmp;
		tmp = tmp->next;
	}
	return (copy);
}

/**
 * =========================================================================
 * FUNCTION: reset_stacks
 * =========================================================================
 * OVERVIEW:
 *  Restores stack nodes back to their original circular order using the
 *  snapshot pointer array. Clears stack B, resets stack size counters,
 *  and zeroes the metrics tracker for the next sorting run.
 *
 * EXECUTION SCHEMA:
 *
 *   copy[0], copy[1], ..., copy[size - 1]
 *         │
 *         ▼
 *   Loop i from 0 to size - 1:
 *         copy[i]->next = copy[(i + 1) % size]
 *         copy[i]->prev = copy[(i + size - 1) % size]
 *         │
 *         ▼
 *   config->nums.a = copy[0]
 *   config->nums.b = NULL
 *   config->nums.size_a = size, config->nums.size_b = 0
 *   ft_memset(&config->metrics, 0, sizeof(t_bench))
 *
 * PARAMETERS:
 *  - config {t_config *}: Program context containing stacks and metrics.
 *  - copy {t_stack **}: Snapshot array storing original node pointers.
 *
 * RETURNS:
 *  - void: Mutates node links, stack roots, and counters in place.
 *
 * COMPLEXITY:
 *  - Time Complexity:  O(N), where N is config->nums.size.
 *  - Space Complexity: O(1) auxiliary space.
 *
 * EDGE CASES & ASSUMPTIONS:
 *  - Uses modular arithmetic to link tail to head without index underflow.
 *  - Guarantees clean isolation between simulated dry-runs.
 * =========================================================================
 */
static void	reset_stacks(t_config *config, t_stack **copy)
{
	int	size;
	int	i;

	size = config->nums.size;
	i = 0;
	while (i < size)
	{
		copy[i]->next = copy[(i + 1) % size];
		copy[i]->prev = copy[(i + size - 1) % size];
		i++;
	}
	config->nums.a = copy[0];
	config->nums.b = NULL;
	config->nums.size_a = size;
	config->nums.size_b = 0;
	ft_memset(&config->metrics, 0, sizeof(config->metrics));
}

/**
 * =========================================================================
 * FUNCTION: try_k
 * =========================================================================
 * OVERVIEW:
 *  Executes a single sorting dry run using a specific pivot ratio (k / 20).
 *  Rebuilds initial stack state, runs sort_a, and returns the total
 *  instruction count generated by that partition setup.
 *
 * EXECUTION SCHEMA:
 *
 *   config->pivot = pivot
 *         │
 *         ▼
 *   reset_stacks(config, copy)   ──> Restore initial layout & zero metrics
 *         │
 *         ▼
 *   sort_a(config, arr, size)    ──> Run sorting simulation
 *         │
 *         ▼
 *   Return (long)config->metrics.total
 *
 * PARAMETERS:
 *  - config {t_config *}: Program context containing runtime settings.
 *  - copy {t_stack **}: Snapshot array of original node pointers.
 *  - pivot {int}: Pivot partition ratio candidate (e.g., 8 to 12).
 *
 * RETURNS:
 *  - {long}: Total instruction moves performed during this trial.
 *
 * COMPLEXITY:
 *  - Time Complexity:  O(T(sort_a)), the cost of running sort_a.
 *  - Space Complexity: O(1) auxiliary space.
 *
 * EDGE CASES & ASSUMPTIONS:
 *  - All mutations are contained because reset_stacks resets state next.
 * =========================================================================
 */
static long	try_k(t_config *config, t_stack **copy, int pivot)
{
	config->pivot = pivot;
	reset_stacks(config, copy);
	sort_a(config, config->nums.arr, config->nums.size);
	return ((long)config->metrics.total);
}

/**
 * =========================================================================
 * FUNCTION: search
 * =========================================================================
 * OVERVIEW:
 *  Sweeps pivot partition candidates k from 8 to 12 (representing 40/60%
 *  through 60/40% partition splits) via silent dry runs. Returns the ratio
 *  that produces the fewest total operations.
 *
 * EXECUTION SCHEMA:
 *
 *   silent = 1, min = -1, best = 10, k = 8
 *         │
 *         ▼
 *   Loop k from 8 to 12:
 *         │
 *         ├── cost = try_k(config, nodes, k)
 *         ├── (min < 0 || cost < min)? ──> min = cost, best = k
 *         ├── size > 1000? ──────────────> break (Cap simulation budget)
 *         └── k++
 *         │
 *         ▼
 *   silent = 0
 *   Return best
 *
 * PARAMETERS:
 *  - config {t_config *}: Program context containing stacks and settings.
 *  - nodes {t_stack **}: Snapshot array of original node pointers.
 *
 * RETURNS:
 *  - {int}: Best pivot parameter k yielding the lowest operation cost.
 *
 * COMPLEXITY:
 *  - Time Complexity:  O(C * T(sort_a)), where C <= 5 trial iterations.
 *  - Space Complexity: O(1) auxiliary space.
 *
 * EDGE CASES & ASSUMPTIONS:
 *  - Sets silent flag to suppress terminal logs during test runs.
 *  - Breaks early on large sets (size > 1000) to avoid simulation latency.
 *  - Defaults to median split (best = 10) if no cheaper ratio is found.
 * =========================================================================
 */
static int	search(t_config *config, t_stack **nodes)
{
	long	cost;
	long	min;
	int		best;
	int		k;

	min = -1;
	best = 10;
	config->silent = 1;
	k = 8;
	while (k <= 12)
	{
		cost = try_k(config, nodes, k);
		if (min < 0 || cost < min)
		{
			min = cost;
			best = k;
		}
		k++;
		if (config->nums.size > 1000)
			break ;
	}
	config->silent = 0;
	return (best);
}

/**
 * =========================================================================
 * FUNCTION: calculate_pivot
 * =========================================================================
 * OVERVIEW:
 *  High-level pivot optimizer for the complex sort strategy. Captures a
 *  snapshot of stack A, searches for the most cost-efficient partition
 *  ratio through dry runs, restores the stack, and saves the winning pivot.
 *
 * EXECUTION SCHEMA:
 *
 *   nodes = copy_stack(config)   ──> Snapshot initial node order
 *         │
 *         ▼
 *   best = search(config, nodes) ──> Evaluate ratios [8..12]
 *         │
 *         ▼
 *   reset_stacks(config, nodes)  ──> Rebuild original stack A and clear B
 *         │
 *         ▼
 *   config->pivot = best
 *
 * PARAMETERS:
 *  - config {t_config *}: Program context to configure with optimal pivot.
 *
 * RETURNS:
 *  - void: Modifies config->pivot and leaves stack A fully restored.
 *
 * COMPLEXITY:
 *  - Time Complexity:  O(C * T(sort_a)), where C <= 5 trial iterations.
 *  - Space Complexity: O(N) heap memory for node snapshot array.
 *
 * EDGE CASES & ASSUMPTIONS:
 *  - Guarantees stack A returns to its exact pre-simulation configuration.
 *  - Leaves stack B empty and metrics zeroed before real sorting begins.
 * =========================================================================
 */
void	calculate_pivot(t_config *config)
{
	t_stack	**nodes;
	int		best;

	nodes = copy_stack(config);
	best = search(config, nodes);
	reset_stacks(config, nodes);
	config->pivot = best;
}
